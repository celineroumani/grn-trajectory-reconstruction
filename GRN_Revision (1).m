dg1dt = ...
    alpha1 ...
    / ...
    (1 + g2^nHill) ...
    - delta1*g1;
dg2dt = ...
    alpha2 ...
    / ...
    (1 + g1^nHill) ...
    - delta2*g2;
dydt = [
    dg1dt
    dg2dt
    ];
end
