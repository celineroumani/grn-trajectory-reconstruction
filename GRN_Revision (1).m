    wF*mseF ...
    + wObs*mseObs;
gradients = ...
    dlgradient( ...
    loss, ...
    net.Learnables);
end
function [ ...
    net, ...
    solverState, ...
    iteration, ...
    lossCell,stopReason ...
    ] = ...
    runLBFGS_collectLoss( ...
    net, ...
    lossFcn, ...
    maxIt, ...
    gradTol, ...
    stepTol)
solverState = ...
    lbfgsState;
iteration = 0;
stopReason = "Iteration limit";
lossCell = ...
    cell( ...
    maxIt, ...
    1 );
while iteration < maxIt
    iteration = ...
        iteration + 1;
    [ ...
        net, ...
        solverState ...
        ] = ...
        lbfgsupdate( ...
        net, ...
        lossFcn, ...
        solverState);
    lossCell{iteration} = ...
        solverState.Loss;
    stopGrad = ...
        solverState.GradientsNorm ...
        < gradTol;
    stopStep = ...
        solverState.StepNorm ...
        < stepTol;
    lsFailed = strcmpi(solverState.LineSearchStatus,'failed');
    if mod(iteration,100) == 0
        fprintf( ...
            ['Iteration %4d | ' ...
             'Loss = %.4e | ' ...
             'GradNorm = %.4e | ' ...
             'StepNorm = %.4e\n'], ...
            iteration, ...
            dlscalarToDouble( ...
            solverState.Loss), ...
            solverState.GradientsNorm, ...
            solverState.StepNorm);
    end
    if lsFailed
        stopReason = "Line search failed";
    elseif stopGrad
        stopReason = "Gradient tolerance";
    elseif stopStep
        stopReason = "Step tolerance";
    end
    if lsFailed || stopGrad || stopStep
        break;
    end
end
lossCell = ...
    lossCell( ...
    1:iteration);
end
function v = ...
    lossCellToNumeric( ...
    lossCell)
n = ...
    numel(lossCell);
v = ...
    zeros( ...
    n, ...
    1 );
for i = 1:n
    v(i) = ...
        dlscalarToDouble( ...
        lossCell{i});
end
end
function y = ...
    dlscalarToDouble(x)
try
    y = ...
        double( ...
        gather( ...
        extractdata(x)));
catch
    y = ...
        double(x);
end
end

function [loss,gradients] = modelLoss_L2_GRN(net,Tobs,Yobs,lambda)
prediction = forward(net,Tobs);
loss = mean((prediction-Yobs).^2,'all');
learnables = net.Learnables;
weights = learnables.Value(string(learnables.Parameter) == "Weights");
for k = 1:numel(weights)
    loss = loss + lambda*sum(weights{k}.^2,'all');
end
gradients = dlgradient(loss,learnables);
end

function residual = odeFitResidual(initial,odeRhs,tObs,Yobs,options)
solution = ode45(odeRhs,[tObs(1) tObs(end)],initial,options);
difference = deval(solution,tObs)-Yobs;
residual = difference(:);
end

function row = supplementalRow(row,label,Yhat,Ytrue,YobsHat,Yobs,runtime, ...
    iterations,finalLoss,finalGradNorm,stopReason)
rmse = sqrt(mean((Yhat-Ytrue).^2,2));
relativeL2 = vecnorm(Yhat-Ytrue,2,2)./vecnorm(Ytrue,2,2);
row.Model = {label};
row.RMSE_Gene1 = rmse(1);
row.RMSE_Gene2 = rmse(2);
row.RMSE_Avg = mean(rmse);
row.RelL2_Gene1 = relativeL2(1);
row.RelL2_Gene2 = relativeL2(2);
row.RelL2_Avg = mean(relativeL2);
row.Observation_RMSE = sqrt(mean((YobsHat-Yobs).^2,'all'));
row.Runtime_s = runtime;
row.Iterations = iterations;
row.FinalLoss = finalLoss;
row.FinalGradientNorm = finalGradNorm;
row.StopReason = stopReason;
end

function exportRevisionSummary(runs,clipping,obsGrid,noiseGrid,n,l2Grid,maxIt,outputRoot,summaryRoot)
levels = 100*noiseGrid;
paired = table();
conditions = table();
comparisons = table();
clipSummary = table();
df = n-1;
betaQuantile = betaincinv(0.05,df/2,0.5);
tCritical = sqrt(df*(1-betaQuantile)/betaQuantile);
labels = [{'NN','PINN'},arrayfun(@(x) sprintf('NN-L2 %g',x),l2Grid, ...
    'UniformOutput',false),{'ODE fit'}];

for level = levels
    noiseClips = clipping(clipping.NoisePercent == level,:);
    perGene = sum(noiseClips.ValuesPerGene);
    gene1 = sum(noiseClips.ClippedGene1);
    gene2 = sum(noiseClips.ClippedGene2);
    clipSummary = [clipSummary; table(level,height(noiseClips),gene1,gene2, ...
        perGene,gene1+gene2,2*perGene,100*(gene1+gene2)/(2*perGene), ...
        'VariableNames',{'NoisePercent','Datasets','ClippedGene1','ClippedGene2', ...
        'ValuesPerGene','ClippedTotal','ValuesTotal','PercentClipped'})];
    for obs = obsGrid
        condition = runs(runs.Nobs == obs & runs.NoisePercent == level,:);
        nn = sortrows(condition(strcmp(condition.Model,'NN'),:),'Repetition');
        pinn = sortrows(condition(strcmp(condition.Model,'PINN'),:),'Repetition');
        keys = {'Repetition','DataSeed','InitSeed'};
        assert(height(nn) == n && isequal(nn(:,keys),pinn(:,keys)), ...
            'Expected %d matched runs for Nobs=%d, noise=%g%%.',n,obs,level);
        delta = nn.RMSE_Avg-pinn.RMSE_Avg;
        paired = [paired; table(nn.Nobs,nn.NoisePercent,nn.Repetition,nn.DataSeed, ...
            nn.InitSeed,nn.RMSE_Avg,pinn.RMSE_Avg,delta,'VariableNames', ...
            {'Nobs','NoisePercent','Repetition','DataSeed','InitSeed', ...
            'NN_RMSE','PINN_RMSE','NN_minus_PINN'})];
        avg = mean(delta);
        sd = std(delta,0);
        margin = tCritical*sd/sqrt(n);
        conditions = [conditions; table(obs,level,n,mean(nn.RMSE_Avg), ...
            std(nn.RMSE_Avg,0),mean(pinn.RMSE_Avg),std(pinn.RMSE_Avg,0), ...
            mean(nn.RMSE_Avg)/mean(pinn.RMSE_Avg),sum(delta>0),avg,sd, ...
            median(delta),avg-margin,avg+margin,'VariableNames', ...
            {'Nobs','NoisePercent','MatchedRuns','NN_MeanRMSE','NN_SDRMSE', ...
            'PINN_MeanRMSE','PINN_SDRMSE','NN_to_PINN_Ratio','PairsFavoringPINN', ...
            'MeanPairedDifference','SDPairedDifference','MedianPairedDifference', ...
            'PairedMeanCI95_Lower','PairedMeanCI95_Upper'})];
        for k = 1:numel(labels)
            method = sortrows(condition(strcmp(condition.Model,labels{k}),:),'Repetition');
            assert(isequal(method(:,keys),pinn(:,keys)), ...
                'Incomplete or mismatched results for %s.',labels{k});
            diffFromPINN = method.RMSE_Avg-pinn.RMSE_Avg;
            marginK = tCritical*std(diffFromPINN,0)/sqrt(n);
            comparisons = [comparisons; table(obs,level,string(labels{k}), ...
                mean(method.RMSE_Avg),std(method.RMSE_Avg,0), ...
                mean(diffFromPINN),median(diffFromPINN),sum(diffFromPINN>0), ...
                mean(diffFromPINN)-marginK,mean(diffFromPINN)+marginK, ...
                'VariableNames',{'Nobs','NoisePercent','Model','MeanRMSE','SDRMSE', ...
                'MeanDifferenceFromPINN','MedianDifferenceFromPINN','PairsFavoringPINN', ...
                'DiffFromPINN_CI95_Lower','DiffFromPINN_CI95_Upper'})];
        end
    end
end
writetable(paired,fullfile(summaryRoot,'Paired_RMSE_Differences.csv'));
writetable(conditions,fullfile(summaryRoot,'Manuscript_Condition_Results.csv'));
writetable(comparisons,fullfile(summaryRoot,'Supplementary_Baselines.csv'));
writetable(clipping,fullfile(summaryRoot,'Clipping_Per_Dataset.csv'));
writetable(clipSummary,fullfile(summaryRoot,'Clipping_By_Noise.csv'));

neural = runs(~strcmp(runs.Model,'ODE fit'),:);
stops = unique(neural.StopReason,'stable');
convergence = table();
for k = 1:numel(labels)-1
    method = neural(strcmp(neural.Model,labels{k}),:);
    for reason = stops(:)'
        convergence = [convergence; table(string(labels{k}),reason, ...
            sum(method.StopReason == reason),'VariableNames', ...
            {'Model','StopReason','Runs'})];
    end
end
writetable(convergence,fullfile(summaryRoot,'Convergence_Stop_Counts.csv'));

primary = runs(ismember(runs.Model,{'NN','PINN'}),:);
trainingCost = table();
for k = 1:2
    method = primary(strcmp(primary.Model,labels{k}),:);
    trainingCost = [trainingCost; table(string(labels{k}),height(method), ...
        mean(method.Runtime_s),std(method.Runtime_s,0),mean(method.Iterations), ...
        std(method.Iterations,0),sum(method.Iterations == maxIt), ...
        sum(method.StopReason == "Iteration limit"), ...
        'VariableNames',{'Model','Runs','MeanRuntime_s','SDRuntime_s', ...
        'MeanIterations','SDIterations','RunsReachingIterationCap', ...
        'StoppedByIterationLimit'})];
end
writetable(trainingCost,fullfile(summaryRoot,'Manuscript_Training_Cost.csv'));
l2Rows = startsWith(comparisons.Model,"NN-L2");
sharedValues = [primary.RMSE_Avg; comparisons.MeanRMSE(l2Rows)];
assert(all(isfinite(sharedValues) & sharedValues>0), ...
    'Log-scale figures require finite positive RMSE.');
sharedLimits = [10^floor(log10(min(sharedValues))) 10^ceil(log10(max(sharedValues)))];
plotManuscriptRMSE(primary,conditions,obsGrid,levels,summaryRoot,sharedLimits);
plotBaselineRMSE(comparisons,obsGrid,levels,l2Grid,summaryRoot,sharedLimits);
plotManuscriptReconstructions(outputRoot,summaryRoot);
end

function plotManuscriptRMSE(primary,conditions,obsGrid,levels,summaryRoot,limits)
fig = figure('Name','Figure 1: Dense-grid RMSE','Color','w','Visible','off', ...
    'Position',[100 100 1000 690]);
layout = tiledlayout(fig,2,2,'Padding','compact','TileSpacing','compact');
colors = [0.19 0.40 0.69; 0.83 0.36 0.16];
labels = {'NN','PINN'};
positions = 1:numel(obsGrid);
for p = 1:numel(levels)
    ax = nexttile(layout);
    hold(ax,'on');
    panel = conditions(conditions.NoisePercent == levels(p),:);
    means = [panel.NN_MeanRMSE panel.PINN_MeanRMSE];
    meanLines = gobjects(1,2);
    for k = 1:2
        color = colors(k,:);
        for j = positions
            rows = primary.NoisePercent == levels(p) & primary.Nobs == obsGrid(j) ...
                & strcmp(primary.Model,labels{k});
            errors = primary.RMSE_Avg(rows);
            offset = (2*k-3)*0.09 + linspace(-0.045,0.045,numel(errors))';
            plot(ax,j+offset,errors,'o','Color',color,'MarkerSize',3, ...
                'HandleVisibility','off');
        end
        meanLines(k) = plot(ax,positions,means(:,k),'-o','Color',color, ...
            'MarkerFaceColor',color,'LineWidth',1.25,'MarkerSize',5);
    end
    set(ax,'YScale','log','XTick',positions,'XTickLabel',string(obsGrid));
    xlim(ax,[0.65 positions(end)+0.35]);
    ylim(ax,limits);
    grid(ax,'on');
    title(ax,sprintf('(%c) %g%% noise','a'+p-1,levels(p)));
    if p == 1
        legend(ax,meanLines,labels,'Location','best');
    end
end
xlabel(layout,'Number of observation times');
ylabel(layout,'Dense-grid RMSE');
exportManuscriptFigure(fig,summaryRoot,'Figure_1_Dense_Grid_RMSE');
end

