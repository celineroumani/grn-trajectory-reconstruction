function [loss,gradients] = ...
    modelLoss_PINN_GRN( ...
    net, ...
    Tf, ...
    Tobs, ...
    Yobs, ...
    wF, ...
    wObs, ...
    alpha1, ...
    alpha2, ...
    delta1, ...
    delta2, ...
    nHill)
Ytemp1 = ...
    forward( ...
    net, ...
    Tf);
G1temp = ...
    Ytemp1(1,:);
dG1dt = ...
    dlgradient( ...
    sum( ...
    G1temp, ...
    'all'), ...
    Tf, ...
    EnableHigherDerivatives=true);
Ytemp2 = ...
    forward( ...
    net, ...
    Tf);
G2temp = ...
    Ytemp2(2,:);
dG2dt = ...
    dlgradient( ...
    sum( ...
    G2temp, ...
    'all'), ...
    Tf, ...
    EnableHigherDerivatives=true);
Yf = ...
    forward( ...
    net, ...
    Tf);
G1 = ...
    Yf(1,:);
G2 = ...
    Yf(2,:);
rhs1 = ...
    alpha1 ...
    ./ ...
    (1 + G2.^nHill) ...
    - delta1.*G1;
rhs2 = ...
    alpha2 ...
    ./ ...
    (1 + G1.^nHill) ...
    - delta2.*G2;
f1 = ...
    dG1dt ...
    - rhs1;
f2 = ...
    dG2dt ...
    - rhs2;
mseF = ...
    mean( ...
    f1.^2 ...
    + f2.^2, ...
    'all');
YobsPred = ...
    forward( ...
    net, ...
    Tobs);
